// The South Fields' books (UPGRADE_PLAN_14.md phase 5): for every crop, what a plot makes a day across a season of
// 28 dawns - seed bought (or, for the rare and charmed, found), sown, watered every day, picked at two stars and at
// five, sold at the market stall at its worth (no demand bonus) - and the crew's wage against it.
//   node tools/fieldbot.js           print the table and write FIELDS.md
const fs = require("fs"), path = require("path");
const { load } = require("./headless.js");
const CM = load(), SEASON = 28, out = [];
const rows = Object.entries(CM.CROPS).filter(([, K]) => K.price).map(([id, K]) => {
  let day = 0, picks = 0, seeds = 0, first = true;
  while (true) { const need = first || !K.regrow ? K.days : K.regrow; if (day + need > SEASON) break; day += need; picks++; if (first || !K.regrow) seeds++; first = false; if (!K.regrow) { /* a new seed each time */ } }
  const take = (q) => picks * (K.yields || 1) * Math.round(K.price * (1 + 0.25 * (q - 1)));
  const cost = seeds * (K.seedPrice || 0), two = (take(2) - cost) / SEASON, five = (take(5) - cost) / SEASON;
  return { id, name: K.name, kind: K.charmed ? "charmed" : K.rare ? "rare" : "shed", seasons: K.sow.join("/"), days: K.days, regrow: K.regrow || "-", picks, two, five };
}).sort((a, b) => b.two - a.two);
const wage = CM.FIELDHANDS ? CM.FIELDHANDS.wage / CM.FIELDHANDS.jobs : 0;
out.push("# The South Fields' books", "", "GENERATED by tools/fieldbot.js. A plot's takings a day over a season of 28 dawns, watered every day, sold at",
  "the market stall at its worth (no demand bonus), seed bought from the shed (the rare and charmed are found, so free).",
  `A field hand costs about ${wage.toFixed(2)} gold a job (a sowing, a watering, a picking or a weeding).`, "",
  "| Crop | Kind | Seasons | Days | Again | Picks | Gold a day at ★★ | at ★★★★★ |", "|---|---|---|---|---|---|---|---|");
for (const r of rows) out.push(`| ${r.name} | ${r.kind} | ${r.seasons} | ${r.days} | ${r.regrow} | ${r.picks} | ${r.two.toFixed(1)} | ${r.five.toFixed(1)} |`);
const shed = rows.filter((r) => r.kind === "shed"), med = shed.map((r) => r.two).sort((a, b) => a - b)[Math.floor(shed.length / 2)];
out.push("", `The shed's crops: ${Math.min(...shed.map((r) => r.two)).toFixed(1)} to ${Math.max(...shed.map((r) => r.two)).toFixed(1)} gold a plot a day at two stars (the middle one ${med.toFixed(1)}).`);
fs.writeFileSync(path.join(__dirname, "..", "FIELDS.md"), out.join("\n") + "\n");
console.log(out.join("\n"));
