"""dolls.py: pack the heroes' doll tiles (src/art/pixel/d.*.png - Dungeon Crawl Stone Soup, CC0) into one small atlas,
written as src/js/35e-dolls.js (CM.dolls). The portraits of every look are composed from them (36-looks.js)."""
import base64, glob, io, json, math, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
files = sorted(glob.glob(os.path.join(ROOT, "src", "art", "pixel", "d.*.png")))
SIZE = 32
cols = 8
rows = math.ceil(len(files) / cols)
atlas = Image.new("RGBA", (cols * SIZE, rows * SIZE), (0, 0, 0, 0))
index = {}
for i, f in enumerate(files):
    im = Image.open(f).convert("RGBA")
    assert im.size == (SIZE, SIZE), f
    x, y = (i % cols) * SIZE, (i // cols) * SIZE
    atlas.paste(im, (x, y))
    index[os.path.basename(f)[:-4]] = [x, y]
buf = io.BytesIO()
atlas.save(buf, "PNG", optimize=True)
data = base64.b64encode(buf.getvalue()).decode("ascii")
out = os.path.join(ROOT, "src", "js", "35e-dolls.js")
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// GENERATED by tools/dolls.py from src/art/pixel/d.*.png - do not edit.\n")
    fh.write("// The heroes' dolls: Dungeon Crawl Stone Soup tiles (CC0, see src/art/CREDITS.txt), one small atlas; every look's\n")
    fh.write("// portraits are composed from them (36-looks.js), the drawn portrait standing in only until the atlas is decoded.\n")
    fh.write("CM.dolls = { size: %d, index: %s,\n  atlas: \"data:image/png;base64,%s\" };\n" % (SIZE, json.dumps(index, separators=(",", ":")), data))
print("dolls:", len(files), "tiles ->", out, len(data) // 1024, "KB")
